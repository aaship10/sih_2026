    def _spawn_and_launch_racer(self) -> None:
        if not self.ego or not self.ego.is_alive:
            return
        ego_wp = self.map.get_waypoint(self.ego.get_location(), project_to_road=True, lane_type=carla.LaneType.Driving)
        if ego_wp is None:
            return
        behind_dist = random.uniform(RACER_BEHIND_MIN_M, RACER_BEHIND_MAX_M)
        route = ego_wp.previous(behind_dist)
        if not route:
            return
        tf = route[0].transform
        tf.location.z += 0.3
        side = random.choice([-1, 1])  # -1 => overtakes from the left, +1 => from the right
        right = tf.get_right_vector()
        tf.location.x += right.x * side * random.uniform(2.5, 3.2)
        tf.location.y += right.y * side * random.uniform(2.5, 3.2)
        name = random.choice(BIKES)
        actor = self.world.try_spawn_actor(self.bp.find(name), tf)
        if actor is None:
            return
        actor.set_simulate_physics(True)
        actor.set_enable_gravity(True)
        actor.set_autopilot(True, self.tm_port)
        self.tm.ignore_lights_percentage(actor, 100.0)
        self.tm.ignore_signs_percentage(actor, 100.0)
        self.tm.ignore_vehicles_percentage(actor, 60.0)
        self.tm.auto_lane_change(actor, True)
        self.tm.vehicle_percentage_speed_difference(actor, RACER_SPEED_DIFFERENCE)
        self.tm.distance_to_leading_vehicle(actor, 1.0)
        self.racers.append({"actor": actor, "spawn_time": self.sim_time, "side": side})
        print(f"[RUNTIME] RACER_SPAWN actor={actor.id} type={name} side={'left' if side < 0 else 'right'} "
              f"behind={behind_dist:.1f}m ego_turning={self._is_ego_turning()}", flush=True)

    def _maybe_spawn_racer(self) -> None:
        if self.sim_time < self.next_racer_time:
            return
        self._spawn_and_launch_racer()
        cooldown = random.uniform(RACER_SPAWN_COOLDOWN_MIN_S, RACER_SPAWN_COOLDOWN_MAX_S)
        if self._is_ego_turning() and random.random() < RACER_TURN_BONUS_CHANCE:
            cooldown *= RACER_TURN_COOLDOWN_SCALE  # sneak another one in while the ego is mid-turn
        self.next_racer_time = self.sim_time + cooldown

    def _update_racers(self) -> None:
        if not self.ego or not self.ego.is_alive:
            self.racers = []
            return
        survivors = []
        for item in self.racers:
            actor = item["actor"]
            if not actor.is_alive:
                continue
            age = self.sim_time - item["spawn_time"]
            far_ahead = (not self._is_behind_ego(actor.get_location())
                         and actor.get_location().distance(self.ego.get_location()) > 40.0)
            if age > RACER_LIFETIME_S or far_ahead:
                try:
                    actor.destroy()
                except RuntimeError:
                    pass
                continue
            survivors.append(item)
        self.racers = survivors

