    def _find_junction(self, tf):
        wp = self.map.get_waypoint(tf.location)
        travelled = 0.0
        previous = wp
        while travelled < JUNCTION_SEARCH_MAX_M:
            nxt = wp.next(2.0)
            if not nxt: return None, None
            wp = nxt[0]; travelled += 2.0
            if wp.is_junction: return wp.get_junction(), previous
            previous = wp
        return None, None

    def _freeze_lights(self) -> None:
        try:
            junction_lights = list(self.world.get_traffic_lights_in_junction(self.junction.id))
        except AttributeError:
            junction_lights = []
        all_lights = list(self.world.get_actors().filter("traffic.traffic_light*"))
        self.lights = list({l.id: l for l in (junction_lights + all_lights)}.values())
        for light in self.lights:
            light.set_state(carla.TrafficLightState.Green)
            light.freeze(True)

    def _candidate_approaches(self):
        result, keys = [], set()
        for entry, exit_wp in self.junction.get_waypoints(carla.LaneType.Driving):
            if self.ego_entry_wp and entry.road_id == self.ego_entry_wp.road_id:
                continue
            key = (entry.road_id, entry.lane_id)
            if key in keys: continue
            if any(entry.transform.location.distance(x[0].transform.location) < 12.0 for x in result):
                continue
            keys.add(key); result.append((entry, exit_wp))
        return result

    def _spawn_cross_vehicles(self, bp) -> None:
        approaches = self._candidate_approaches()
        if not approaches:
            print("[SETUP][WARN] no cross approaches", flush=True); return
        roster = [(name, False) for name in CARS] + [(name, True) for name in BIKES]
        random.shuffle(roster)
        reserved: list[carla.Location] = []
        for index, (name, is_bike) in enumerate(roster):
            entry, exit_wp = approaches[index % len(approaches)]
            slot = index // len(approaches)
            spawn_list = entry.previous(FIRST_QUEUE_BACKOFF_M + slot * QUEUE_SPACING_M)
            if not spawn_list: continue
            tf = spawn_list[0].transform
            if is_bike:
                right = tf.get_right_vector(); side = random.uniform(-0.7, 0.7)
                tf.location.x += right.x * side; tf.location.y += right.y * side
            tf.location.z += 0.3
            if any(tf.location.distance(x) < MIN_SPAWN_SEPARATION_M for x in reserved):
                continue
            vehicle_bp = bp.find(name)
            vehicle_bp.set_attribute("role_name", "physics_cross_traffic")
            actor = self.world.try_spawn_actor(vehicle_bp, tf)
            if actor is None:
                print(f"[SETUP][WARN] failed spawn {name} slot={slot}", flush=True); continue
            reserved.append(carla.Location(tf.location.x, tf.location.y, tf.location.z))
            actor.set_simulate_physics(True)
            actor.set_enable_gravity(True)
            actor.set_autopilot(True, self.tm_port)
            self.tm.ignore_lights_percentage(actor, 100.0)
            self.tm.ignore_signs_percentage(actor, 100.0)
            self.tm.auto_lane_change(actor, True)
            self.tm.random_left_lanechange_percentage(actor, 20.0)
            self.tm.random_right_lanechange_percentage(actor, 20.0)
            # Relaxed collision avoidance + varied speed so crossing paths at
            # the junction produce real collision chances instead of the TM
            # cleanly avoiding every conflict (default ignore_vehicles=0%).
            self.tm.ignore_vehicles_percentage(actor, random.uniform(35.0, 65.0))
            self.tm.vehicle_percentage_speed_difference(actor, random.uniform(-10.0, 35.0))
            self.tm.distance_to_leading_vehicle(actor, 2.0)
            actor.apply_control(carla.VehicleControl(throttle=0.0, brake=1.0, hand_brake=True))
            self.cross.append({"actor": actor, "entry": entry, "exit": exit_wp,
                               "release_time": None, "released": False, "start": carla.Location(tf.location.x, tf.location.y, tf.location.z)})
            print(f"[SETUP] physics vehicle actor={actor.id} type={name} at=({tf.location.x:.1f},{tf.location.y:.1f})", flush=True)

    def _walker_nav_target(self, origin: carla.Location, preferred: carla.Location) -> carla.Location | None:
        """Return a reachable navigation-mesh target for controller.ai.walker."""
        best = None
        best_error = float("inf")
        for _ in range(WALKER_TARGET_RETRIES):
            candidate = self.world.get_random_location_from_navigation()
            if candidate is None:
                continue
            distance = origin.distance(candidate)
            error = candidate.distance(preferred)
            if 5.0 <= distance <= 35.0 and error < best_error:
                best, best_error = candidate, error
        return best

    def _is_behind_ego(self, loc: carla.Location) -> bool:
        if not self.ego or not self.ego.is_alive:
            return False
        tf = self.ego.get_transform()
        forward = tf.get_forward_vector()
        to_actor = loc - tf.location
        return (forward.x * to_actor.x + forward.y * to_actor.y) < 0.0

    def _is_ego_turning(self) -> bool:
        """True while the ego is actively steering or inside/near the junction."""
        if not self.ego or not self.ego.is_alive:
            return False
        steer = abs(self.ego.get_control().steer)
        ego_wp = self.map.get_waypoint(self.ego.get_location())
        near_junction = bool(ego_wp and ego_wp.is_junction) or (
            self.junction is not None
            and self.ego.get_location().distance(self.junction.bounding_box.location) < JUNCTION_TRIGGER_DISTANCE_M
        )
        return steer > RACER_STEER_TURNING_THRESHOLD or near_junction

    # ------------------------------------------------------------------
    # Initial (pre-placed) pedestrians / cattle -- the first wave, present
    # from the start so the road already feels busy.
    # ------------------------------------------------------------------
    def _spawn_walkers(self, bp) -> None:
        walker_bps = bp.filter("walker.pedestrian.*")
        controller_bp = bp.find("controller.ai.walker")
        if not walker_bps or controller_bp is None or not self.ego_entry_wp: return
        for i in range(15):
            back = self.ego_entry_wp.previous(5.0 + i * 4.0)
            wp = back[0] if back else self.ego_entry_wp
            right = wp.transform.get_right_vector()
            side = random.choice([-1, 1]) * random.uniform(1.8, 2.5)
            tf = carla.Transform(carla.Location(wp.transform.location.x + right.x * side,
                                                 wp.transform.location.y + right.y * side,
                                                 wp.transform.location.z + 0.5), wp.transform.rotation)
            walker = self.world.try_spawn_actor(random.choice(walker_bps), tf)
            if walker is None: continue
            preferred = carla.Location(tf.location.x - right.x * side * 2.0,
                                       tf.location.y - right.y * side * 2.0, tf.location.z)
            target = self._walker_nav_target(tf.location, preferred)
            if target is None:
                walker.destroy()
                continue
            controller = self.world.spawn_actor(controller_bp, carla.Transform(), attach_to=walker)
            controller.start()
            controller.go_to_location(target)
            controller.set_max_speed(0.0)
            self.walkers.append({"actor": walker, "controller": controller, "target": target,
                                  "started": False, "spawn_time": 0.0, "sudden": False})
            self.controllers.append(controller)

    def _spawn_cattle(self, bp) -> None:
        walker_bps = bp.filter("walker.pedestrian.*")
        controller_bp = bp.find("controller.ai.walker")
        if not walker_bps or controller_bp is None or not self.ego_entry_wp: return
        for dist in [35.0, 65.0]:
            back = self.ego_entry_wp.previous(dist)
            wp = back[0] if back else self.ego_entry_wp
            right = wp.transform.get_right_vector()
            for i in range(3):
                side = 2.2 + random.uniform(-0.5, 0.5)
                tf = carla.Transform(carla.Location(wp.transform.location.x + right.x * side + random.uniform(-1, 1),
                                                     wp.transform.location.y + right.y * side + random.uniform(-1, 1),
                                                     wp.transform.location.z + 0.5), wp.transform.rotation)
                walker = self.world.try_spawn_actor(random.choice(walker_bps), tf)
                if walker is None: continue
                preferred = carla.Location(tf.location.x - right.x * side * 2.5,
                                           tf.location.y - right.y * side * 2.5, tf.location.z)
                target = self._walker_nav_target(tf.location, preferred)
                if target:
                    controller = self.world.spawn_actor(controller_bp, carla.Transform(), attach_to=walker)
                    controller.start()
                    controller.go_to_location(target)
                    controller.set_max_speed(0.0)
                    self.cattle.append({"actor": walker, "controller": controller, "target": target,
                                         "started": False, "spawn_time": 0.0})
                    self.controllers.append(controller)

    # ------------------------------------------------------------------
    # Continuous jaywalking / cattle spawners -- fire throughout the run so
    # people and animals can appear "anytime, anywhere", including right in
    # front of the ego.
    # ------------------------------------------------------------------
    def _spawn_dynamic_jaywalker(self) -> None:
        walker_bps = self.bp.filter("walker.pedestrian.*")
        controller_bp = self.bp.find("controller.ai.walker")
        if not walker_bps or controller_bp is None or not self.ego or not self.ego.is_alive:
            return
        ego_wp = self.map.get_waypoint(self.ego.get_location(), project_to_road=True, lane_type=carla.LaneType.Driving)
        if ego_wp is None:
            return
        sudden = random.random() < JAYWALK_SUDDEN_CHANCE
        ahead = random.uniform(JAYWALK_SUDDEN_MIN_M, JAYWALK_SUDDEN_MAX_M) if sudden \
            else random.uniform(JAYWALK_AHEAD_MIN_M, JAYWALK_AHEAD_MAX_M)
        route = ego_wp.next(ahead)
        if not route:
            return
        wp = route[0]
        right = wp.transform.get_right_vector()
        side = random.choice([-1, 1])
        start_offset = side * random.uniform(3.0, 5.0)
        spawn_tf = carla.Transform(carla.Location(
            wp.transform.location.x + right.x * start_offset,
            wp.transform.location.y + right.y * start_offset,
            wp.transform.location.z + 0.5), wp.transform.rotation)
        walker = self.world.try_spawn_actor(random.choice(walker_bps), spawn_tf)
        if walker is None:
            return
        target_offset = -side * random.uniform(3.0, 5.0)
        preferred = carla.Location(
            wp.transform.location.x + right.x * target_offset,
            wp.transform.location.y + right.y * target_offset,
            wp.transform.location.z)
        target = self._walker_nav_target(spawn_tf.location, preferred)
        if target is None:
            walker.destroy()
            return
        controller = self.world.spawn_actor(controller_bp, carla.Transform(), attach_to=walker)
        controller.start()
        controller.go_to_location(target)
        # sudden jaywalkers step out immediately; others linger like someone deciding to cross
        controller.set_max_speed(WALKER_MAX_SPEED_MPS * random.uniform(0.8, 1.6) if sudden else 0.0)
        self.walkers.append({"actor": walker, "controller": controller, "target": target,
                              "started": sudden, "spawn_time": self.sim_time, "sudden": sudden})
        self.controllers.append(controller)
        print(f"[RUNTIME] JAYWALK_SPAWN actor={walker.id} sudden={sudden} ahead={ahead:.1f}m side={side}", flush=True)

