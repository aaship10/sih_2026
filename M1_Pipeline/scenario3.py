    def _release_cross_traffic(self, ego_loc) -> None:
        if self.sim_time < SCENARIO_WARMUP_S or self.cross_armed: return
        if ego_loc.distance(self.junction.bounding_box.location) > JUNCTION_TRIGGER_DISTANCE_M: return
        self.cross_armed = True
        for index, cv in enumerate(self.cross):
            cv["release_time"] = self.sim_time + index * RELEASE_INTERVAL_S
        print(f"[RUNTIME] armed {len(self.cross)} physics vehicles", flush=True)

    def _update_cross_traffic(self, ego_loc) -> None:
        survivors = []
        for cv in self.cross:
            actor = cv["actor"]
            if not actor.is_alive:
                continue
            if cv["release_time"] is not None:
                if not cv["released"] and self.sim_time >= cv["release_time"]:
                    cv["released"] = True
                    actor.apply_control(carla.VehicleControl(throttle=0.25, brake=0.0, hand_brake=False))
                    print(f"[RUNTIME] RELEASE actor={actor.id} t={self.sim_time:.2f}", flush=True)
                if cv["released"] and self.sim_time - cv["release_time"] > CROSS_CLEAR_TIME_S:
                    actor.apply_control(carla.VehicleControl(throttle=0.0, brake=1.0, hand_brake=False))
            behind = self._is_behind_ego(actor.get_location())
            if behind and ego_loc.distance(actor.get_location()) > CROSS_VEHICLE_DESPAWN_BEHIND_M:
                try:
                    actor.destroy()
                except RuntimeError:
                    pass
                continue
            survivors.append(cv)
        self.cross = survivors

    def _spawn_dynamic_cross_vehicle(self) -> None:
        approaches = self._candidate_approaches()
